/**
 * @file    rs485.h
 * @brief   RS485 半双工收发方向控制
 *
 * @tag     [2023 实做]  用 RS485 而不是 TTL 串口连 DTU，是有据的选择：
 *          论文 3.3.1 节明确「ATK-IDM751C 只用 RS485-A / RS485-B 两根差分线
 *          加电源」，驱动头文件里也是按 RS485 通讯写的。
 *          选它的理由是差分传输抗共模干扰、可走长线（装在车上/野外），
 *          而不是"速度更快"。
 *
 * @tag     [2026 重建新增]  把「方向控制」单独抽成一个模块。
 *          原代码把方向切换散在收发函数里，一处遗漏就会出现
 *          「发得出去、收不回来」这种最难查的半双工故障。
 *
 * @tag     [未经硬件回归验证]
 *
 * ----------------------------------------------------------------
 * 接线依据（这一条很重要，因为论文表 4-1 是排版错乱的）：
 *
 *   正点原子战舰 STM32F103 板载 RS485 电路使用 SP3485 收发器：
 *     PA2 (USART2_TX)  -> SP3485 的 DI（数据输入）
 *     PA3 (USART2_RX)  <- SP3485 的 RO（数据输出）
 *     PD7              -> SP3485 的 RE#(低有效) 与 DE(高有效)，
 *                         两个引脚短接后由同一个 IO 控制：
 *                             高电平 = 发送模式
 *                             低电平 = 接收模式
 *
 *   【出处】正点原子官方《战舰 V3 第二章 实验平台硬件资源详解》原文：
 *     「RS485_RE 则是直接连接在 MCU 的 IO 口(PD7)上的，该信号用来控制
 *       SP3485 的工作模式(高电平为发送模式，低电平为接收模式)」。
 *   另有两篇 F103 战舰 485 实战文（CSDN / 开源电子网）一致佐证 PA2/PA3/PD7。
 *
 *   【重要提醒】论文表 4-1「各部分具体连接接口」那一栏排版错位了：
 *     ATK-IDM751C 的 VCC / GND / RS485-A / RS485-B 与 PA0 被排到了同一行，
 *     看上去像是「RS485 接在 PA0 上」。真实情况是 PA2/PA3 + PD7。
 *     本工程按上面这个真实接线实现；论文表 4-1 那一栏据实说明为排版错位。
 *
 *   另注：PD7 同时复用为 DM9000_RST（网卡复位），同时用这两个外设时要注意。
 * ----------------------------------------------------------------
 */
#ifndef RS485_H
#define RS485_H

#include <stdint.h>

/** 方向控制脚（战舰板：PD7 -> SP3485 的 RE#/DE） */
#define RS485_RE_PORT       GPIOD
#define RS485_RE_PIN        GPIO_Pin_7

/**
 * @brief 初始化方向控制脚（默认置为接收态，避免一上电就占着总线）
 */
void RS485_Init(void);

/** @brief 切到发送模式（DE 拉高） */
void RS485_SetTx(void);

/** @brief 切回接收模式（DE 拉低） */
void RS485_SetRx(void);

/**
 * @brief 通过 RS485 发送一块数据（自动处理方向切换与发送完成等待）
 * @param data 数据首地址
 * @param len  数据长度
 * @note  这里必须等「发送完成（TC）」而不是「发送数据寄存器空（TXE）」
 *        再切回接收 —— 否则最后一个字节还没移位出去就把 DE 拉低，
 *        那一帧的尾部会被截断。这是半双工 RS485 最经典的坑。
 */
void RS485_SendBuf(const uint8_t *data, uint16_t len);

#endif /* RS485_H */
